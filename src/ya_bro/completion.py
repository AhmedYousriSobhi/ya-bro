"""Tab completion for `broctl`, generated from the real argument parser so it cannot drift.

The script is static (no Python started per Tab): the command tree and the flags are baked in.
`broctl completion bash` prints it; `install()` puts it where bash-completion loads it on demand.
"""

from __future__ import annotations

import argparse
from pathlib import Path

from ya_bro import dirs


def _flags(p: argparse.ArgumentParser) -> list[str]:
    out: list[str] = []
    for a in p._actions:
        if isinstance(a, argparse._SubParsersAction):
            continue
        out += [o for o in a.option_strings if o.startswith("--")]
        if a.choices and not a.option_strings:
            out += [str(c) for c in a.choices]
    return sorted(set(out) - {"--help"}) + ["--help"]


def _tree(p: argparse.ArgumentParser) -> dict:
    """{word: subtree} for each subcommand, plus "": the flags and values valid at this level."""
    node: dict = {"": _flags(p)}
    for a in p._actions:
        if isinstance(a, argparse._SubParsersAction):
            for name, sp in a.choices.items():
                node[name] = _tree(sp)
    return node


def _walk(node: dict, path: str, lines: list[str]) -> None:
    subs = sorted(k for k in node if k)
    lines.append(f'      "{path}") words="{" ".join(subs + node[""])}" ;;')
    for k in subs:
        _walk(node[k], f"{path} {k}".strip(), lines)


def bash_script(parser: argparse.ArgumentParser) -> str:
    cases: list[str] = []
    _walk(_tree(parser), "", cases)
    body = "\n".join(cases)
    return f"""# bash completion for broctl (generated by `broctl completion bash`)
_broctl() {{
  local cur=${{COMP_WORDS[COMP_CWORD]}} path= w words=
  for w in "${{COMP_WORDS[@]:1:COMP_CWORD-1}}"; do
    [[ $w == -* ]] && continue
    path="${{path:+$path }}$w"
  done
  while :; do
    case "$path" in
{body}
      *) words="" ;;
    esac
    # an argument or flag value is not a subcommand: fall back to the last real command's words
    [[ -n $words || $path != *" "* ]] && break
    path=${{path% *}}
  done
  COMPREPLY=($(compgen -W "$words" -- "$cur"))
}}
complete -F _broctl broctl
"""


def script(parser: argparse.ArgumentParser, shell: str) -> str:
    bash = bash_script(parser)
    if shell == "zsh":
        return "autoload -U +X bashcompinit && bashcompinit\n" + bash
    return bash


def target() -> Path:
    # bash-completion loads $XDG_DATA_HOME/bash-completion/completions/<command> on first Tab
    return dirs.data_dir().parent / "bash-completion" / "completions" / "broctl"


def install(parser: argparse.ArgumentParser, where: Path | None = None) -> Path:
    path = where or target()
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(bash_script(parser))
    return path
